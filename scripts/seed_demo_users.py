"""Seed temporary demo users into Supabase (admin API).

Run server-side with the Supabase service-role key:
    SUPABASE_URL=... SUPABASE_SERVICE_KEY=... python scripts/seed_demo_users.py

Creates 3 confirmed users (admin / coach / player), sets roles + plans, and prints
an Ansible-style recap.

Passwords are GENERATED here, one per run, and written to ``.demo-credentials.txt``
(gitignored). They are deliberately not in this file and not in docs/DEMO_ACCESS.md:
the previous hardcoded values were committed to git in plaintext, which puts them in
history permanently and ships them to anyone who clones the repo.

DEMO creds for evaluation only — rotate/disable before real launch.
"""

from __future__ import annotations

import os
import secrets
import sys
from pathlib import Path

CREDS_FILE = Path(__file__).resolve().parents[1] / ".demo-credentials.txt"

DEMO_USERS = [
    {"email": "admin@pvdemo.app",  "role": "admin", "plan": "pro",  "name": "Demo Admin"},
    {"email": "coach@pvdemo.app",  "role": "user",  "plan": "pro",  "name": "Demo Coach"},
    {"email": "player@pvdemo.app", "role": "user",  "plan": "free", "name": "Demo Player"},
]


def new_password() -> str:
    """A fresh URL-safe password. 32 bytes of entropy, prefixed for legibility."""
    return "Pv-" + secrets.token_urlsafe(24)


def write_creds(rows: list[tuple[str, str, str]]) -> None:
    """Write generated credentials to the gitignored file, owner-readable only."""
    body = ["# Generated by scripts/seed_demo_users.py — DEMO ONLY, never commit.",
            "# Each run generates new passwords; the previous ones stop being valid",
            "# only when you rotate them in Supabase.", ""]
    body += [f"{email:22} {password:34} role={role}" for email, password, role in rows]
    CREDS_FILE.write_text("\n".join(body) + "\n", encoding="utf-8")
    try:
        CREDS_FILE.chmod(0o600)  # no-op on Windows; correct on POSIX
    except OSError:
        pass

OK, CHANGED, FAILED = "\033[32m", "\033[33m", "\033[31m"
RESET = "\033[0m"


def main() -> int:
    url = os.getenv("SUPABASE_URL")
    key = os.getenv("SUPABASE_SERVICE_KEY")
    if not url or not key:
        print(f"{FAILED}fatal: set SUPABASE_URL and SUPABASE_SERVICE_KEY{RESET}")
        return 2
    from supabase import create_client

    sb = create_client(url, key)
    print("\nPLAY [seed demo users] " + "*" * 50 + "\n")
    recap = {"ok": 0, "changed": 0, "failed": 0}
    created: list[tuple[str, str, str]] = []

    for u in DEMO_USERS:
        task = f"TASK [create {u['email']}]"
        print(task + " " + "*" * max(2, 60 - len(task)))
        password = new_password()
        try:
            res = sb.auth.admin.create_user({
                "email": u["email"], "password": password, "email_confirm": True,
                "app_metadata": {"role": u["role"]},
                "user_metadata": {"full_name": u["name"]},
            })
            uid = res.user.id
            # set subscription plan (profile + subscription rows are auto-created by trigger)
            sb.table("subscriptions").upsert(
                {"user_id": uid, "plan": u["plan"], "status": "active"}).execute()
            print(f"{CHANGED}changed: [{u['email']}] => "
                  f"{{role={u['role']}, plan={u['plan']}, id={uid[:8]}}}{RESET}\n")
            created.append((u["email"], password, u["role"]))
            recap["changed"] += 1
        except Exception as e:  # noqa: BLE001
            msg = str(e)
            if "already" in msg.lower() or "registered" in msg.lower():
                print(f"{OK}ok: [{u['email']}] => (already exists, skipped){RESET}\n")
                recap["ok"] += 1
            else:
                print(f"{FAILED}failed: [{u['email']}] => {msg}{RESET}\n")
                recap["failed"] += 1

    if created:
        write_creds(created)

    print("PLAY RECAP " + "*" * 60)
    print(f"demo-users : ok={recap['ok']}  changed={recap['changed']}  "
          f"failed={recap['failed']}\n")
    if created:
        print(f"Passwords written to {CREDS_FILE.name} (gitignored). "
              f"Do not commit or paste it.\n")
    else:
        print("No new users created, so no passwords generated. Users that already "
              "exist keep the password they were created with — reset it in Supabase "
              "if you no longer have it.\n")
    return 1 if recap["failed"] else 0


if __name__ == "__main__":
    sys.exit(main())
